<article>
  <section>
    <h2>What Hermes is for</h2>
    <p>
      Hermes is our messenger. It watches the systems we already run, decides what
      is worth surfacing, and delivers it to the right place at the right moment.
      Dodici holds context and does the work. Hermes carries word of it back to us.
    </p>
    <p>
      We did not stand it up because we were short on notifications. We were
      drowning in them. The point of a messenger agent is not more signal. It is
      less noise that actually reaches a person.
    </p>
  </section>

  <section>
    <h2>The setup that mattered</h2>
    <p>
      Most of the install was uneventful. Connect the inbound sources, give it a
      channel to speak through, hand it a model and a memory of what it has already
      said. An afternoon of plumbing.
    </p>
    <p>
      The afternoon was not the hard part. The hard part was deciding, before we
      gave Hermes any initiative at all, what it was allowed to interrupt us for.
      An agent that can reach you is only as good as its judgment about when not to.
    </p>
  </section>

  <section>
    <h2>The rules we set first</h2>
    <ul>
      <li>
        <strong>Thresholds before access.</strong> We defined what counts as worth
        a message before we connected a single source.
      </li>
      <li>
        <strong>One voice, one place.</strong> Hermes speaks in one channel, in a
        consistent format, so a message from it always means the same thing.
      </li>
      <li>
        <strong>Quiet is a feature.</strong> A day with nothing from Hermes is a
        day it did its job, not a day it was idle.
      </li>
      <li>
        <strong>Every message is actionable.</strong> If there is nothing to do
        about it, it is a log entry, not a message.
      </li>
    </ul>
  </section>

  <section>
    <blockquote>
      A messenger you can trust is one that has earned the right to interrupt you.
      That right is configured, not assumed.
    </blockquote>
  </section>

  <section>
    <h2>What it changed</h2>
    <p>
      Within a week the volume of things demanding our attention dropped, and the
      few that did reach us were ones we acted on. That is the whole trade. Hand an
      agent the boring vigilance, keep the decisions, and stop checking dashboards
      that rarely have news.
    </p>
  </section>

  <section>
    <h2>What comes next</h2>
    <p>
      The next step is letting Hermes do more than report. A messenger that
      understands what it is carrying can start to triage, draft a first response,
      and close the simple loops on its own. That is where setup stops and trust
      begins.
    </p>
  </section>
</article>

